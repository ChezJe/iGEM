function row = observationRow(candidate, measurement, batch, index, origin)
    values = [measurement.Fluorescence, measurement.RelativeGrowth, measurement.ObservationSeed];
    if ~isnumeric(values) || numel(values) ~= 3 || ~isreal(values) || ...
            any(~isfinite(values)) || measurement.Fluorescence <= 0 || measurement.RelativeGrowth <= 0
        error("iGEM:VirtualLab:InvalidMeasurement", ...
            "The acquisition must return finite positive paired responses and a finite observation seed.");
    end
    row = table(candidate.CandidateID, candidate.PromoterStrength, candidate.InducerMicromolar, ...
        measurement.Fluorescence, measurement.RelativeGrowth, batch, index, string(origin), ...
        measurement.ObservationSeed, VariableNames=["CandidateID", "PromoterStrength", ...
        "InducerMicromolar", "Fluorescence", "RelativeGrowth", "Batch", "ObservationIndex", ...
        "Origin", "ObservationSeed"]);
end
