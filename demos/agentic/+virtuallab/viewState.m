function view = viewState(state)
    %viewState - Return plot-ready, JSON-serializable virtual-lab results
    %   VIEW = virtuallab.viewState(STATE) exposes observations, predictions,
    %   pending conditions, probabilities, budget, and event messages.
    %   Observed feasibility and predicted probabilities are separate fields.
    %
    %   See also virtuallab.newSession, jsonencode

    arguments
        state (1,1) struct
    end
    validateState(state);
    observations = state.Observations;
    observations.ObservedFeasible = observations.RelativeGrowth >= state.GrowthThreshold;
    candidates = state.Predictions;
    candidates.Observed = ismember(candidates.CandidateID, observations.CandidateID);
    candidates.Proposed = ismember(candidates.CandidateID, state.Proposal.CandidateID);
    feasible = find(observations.ObservedFeasible);
    bestObserved = [];
    if ~isempty(feasible)
        [~, index] = max(observations.Fluorescence(feasible));
        bestObserved = tableRows(observations(feasible(index),:));
    end
    remaining = remainingBudget(state);
    view = struct(seed=state.Seed, modelVersion=state.ModelVersion, status=state.Status, ...
        growthThreshold=state.GrowthThreshold, totalBudget=state.TotalBudget, ...
        usedBudget=state.TotalBudget-remaining, remainingBudget=remaining, ...
        initialCount=state.InitialCount, completedCount=height(observations), ...
        batchNumber=state.BatchNumber, revision=state.Revision, ...
        canPropose=remaining>0 && isempty(state.Proposal), ...
        canRun=remaining>0 && ~isempty(state.Proposal), ...
        lastError=state.LastError.Message, observations=tableRows(observations), ...
        proposal=tableRows(state.Proposal), candidates=tableRows(candidates), ...
        events=tableRows(state.Events), bestObserved=bestObserved, ...
        acquisitionMode=state.AcquisitionMode, ...
        predictionStale=state.PredictionRevision~=state.Revision, ...
        modelDescription="Illustrative SimBiology reporter-expression and growth-burden model", ...
        scienceNote="Predicted probabilities describe unmeasured outcomes, not guarantees. " + ...
        "Growth is the terminal specific growth rate relative to an unburdened reference; " + ...
        "fluorescence is scaled mature-reporter concentration in arbitrary units. " + ...
        "All observations are simulated, not wet-lab data.");
end

function rows = tableRows(values)
    names = string(values.Properties.VariableNames);
    lowerNames = lower(extractBefore(names,2)) + extractAfter(names,1);
    lowerNames(names=="CandidateID") = "candidateId";
    values.Properties.VariableNames = cellstr(lowerNames);
    rows = table2struct(values);
end
