function model = createModel()
    %createModel - Construct an illustrative reporter and growth model
    %   MODEL = virtuallab.createModel() creates a SimBiology model with
    %   transcription, translation, reporter maturation, degradation,
    %   growth dilution, and a phenomenological expression burden.
    %   The parameters are illustrative, not experimentally calibrated.
    %
    %   See also virtuallab.simulateCondition, simBiologyModelBuilder

    model = sbiomodel("VirtualLabReporterGrowth");
    model.Notes = "Illustrative, uncalibrated reporter-expression model. " + ...
        "Fluorescence is a scaled mature-reporter concentration; relative " + ...
        "growth is the terminal specific growth rate divided by its " + ...
        "unburdened value. Both readouts come from one simulation.";
    model.UserData = struct(ModelVersion="1.0.0", EndpointHours=8, ...
        FluorescenceInterpretation="Mature reporter / 1 nanomolar, arbitrary units", ...
        GrowthInterpretation="Terminal specific growth rate / unburdened rate");
    cellCompartment = addcompartment(model, "Cell", 1);
    cellCompartment.Units = "liter";
    speciesNames = ["mRNA", "ImmatureReporter", "MatureReporter"];
    for index = 1:numel(speciesNames)
        species = addspecies(cellCompartment, speciesNames(index), 0);
        species.Units = "nanomolarity";
    end
    names = ["PromoterStrength", "Inducer", "InductionHalfMax", ...
        "BasalFraction", "TranscriptionRate", "TranslationRate", ...
        "MaturationRate", "MRNADecay", "ReporterDecay", ...
        "TranslationCapacity", "MRNABurdenScale", "ProteinBurdenScale", ...
        "InducerBurdenScale", "InducerBurdenWeight", ...
        "UnburdenedGrowthRate", "GrowthRate", "FluorescenceScale"];
    values = [1, 30, 25, 0.025, 7, 9, 1.8, 1.6, 0.12, ...
        20, 45, 500, 100, 0.10, 0.8, 0.8, 1];
    units = ["dimensionless", "micromolarity", "micromolarity", ...
        "dimensionless", "nanomolarity/hour", "1/hour", "1/hour", ...
        "1/hour", "1/hour", "nanomolarity", "nanomolarity", ...
        "nanomolarity", "micromolarity", "dimensionless", ...
        "1/hour", "1/hour", "nanomolarity"];
    for index = 1:numel(names)
        parameter = addparameter(model, names(index), values(index));
        parameter.Units = units(index);
    end
    growth = sbioselect(model, Type="parameter", Name="GrowthRate");
    growth.Constant = false;
    addrule(model, "GrowthRate = UnburdenedGrowthRate/(1 + " + ...
        "Cell.mRNA/MRNABurdenScale + " + ...
        "(Cell.ImmatureReporter + Cell.MatureReporter)/ProteinBurdenScale + " + ...
        "InducerBurdenWeight*(Inducer/InducerBurdenScale)^2)", "repeatedAssignment");
    equations = ["null -> Cell.mRNA", "Cell.mRNA -> null", ...
        "null -> Cell.ImmatureReporter", ...
        "Cell.ImmatureReporter -> Cell.MatureReporter", ...
        "Cell.ImmatureReporter -> null", "Cell.MatureReporter -> null"];
    rates = [ ...
        "Cell*TranscriptionRate*PromoterStrength*(BasalFraction + " + ...
        "(1-BasalFraction)*Inducer^2/(InductionHalfMax^2 + Inducer^2))", ...
        "Cell*(MRNADecay + GrowthRate)*Cell.mRNA", ...
        "Cell*TranslationRate*Cell.mRNA/(1 + Cell.mRNA/TranslationCapacity)", ...
        "Cell*MaturationRate*Cell.ImmatureReporter", ...
        "Cell*(ReporterDecay + GrowthRate)*Cell.ImmatureReporter", ...
        "Cell*(ReporterDecay + GrowthRate)*Cell.MatureReporter"];
    reactionNames = ["Transcription", "MRNATurnover", "Translation", ...
        "Maturation", "ImmatureTurnover", "MatureTurnover"];
    for index = 1:numel(equations)
        reaction = addreaction(model, equations(index));
        reaction.Name = reactionNames(index);
        reaction.ReactionRate = rates(index);
    end
    config = getconfigset(model, "active");
    config.StopTime = 8;
    config.TimeUnits = "hour";
    config.SolverType = "ode15s";
    config.MaximumWallClock = 10;
    config.CompileOptions.UnitConversion = true;
    config.CompileOptions.DimensionalAnalysis = true;
    config.SolverOptions.RelativeTolerance = 1e-6;
    config.SolverOptions.AbsoluteTolerance = 1e-8;
    config.RuntimeOptions.StatesToLog = [model.Species; growth];
end
